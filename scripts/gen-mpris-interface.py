#!/usr/bin/env python3
"""Generate data/mpris-dbus-interface.xml from the vendored MPRIS specification.

Reads doc/specs/mpris/org.mpris.MediaPlayer2*.xml, drops the telepathy `tp:`
documentation markup that gdbus-codegen does not need, and writes the plain
D-Bus introspection XML that meson feeds to gdbus-codegen. Run by
scripts/vendor-specs.sh; run it by hand after editing the vendored files.
"""

import re
import sys
from pathlib import Path
import xml.etree.ElementTree as ET

root = Path(__file__).resolve().parent.parent
spec_dir = root / 'doc' / 'specs' / 'mpris'
out_path = root / 'data' / 'mpris-dbus-interface.xml'

# Order matters: it is the order of the interfaces in the generated code.
FILES = [
    'org.mpris.MediaPlayer2.xml',
    'org.mpris.MediaPlayer2.Player.xml',
    'org.mpris.MediaPlayer2.TrackList.xml',
    'org.mpris.MediaPlayer2.Playlists.xml',
]
# Elements that belong to plain D-Bus introspection; everything else
# (tp:docstring, tp:enum, tp:struct, ...) is documentation markup.
KEEP = {'interface', 'method', 'signal', 'property', 'arg', 'annotation'}


def local(tag):
    return tag.rsplit('}', 1)[-1] if '}' in tag else tag


def is_foreign(name):
    return name.startswith('{')


def clean(element):
    """Copy of `element` without tp: attributes and non-introspection children."""
    copy = ET.Element(local(element.tag))
    for key, value in element.attrib.items():
        if not is_foreign(key):
            copy.set(key, value)
    for child in element:
        if is_foreign(child.tag) or local(child.tag) not in KEEP:
            continue
        copy.append(clean(child))
    return copy


def main():
    node = ET.Element('node')
    for name in FILES:
        tree = ET.parse(spec_dir / name)
        for interface in tree.getroot().iter('interface'):
            node.append(clean(interface))
    ET.indent(node, space='  ')
    body = ET.tostring(node, encoding='unicode')

    revision = re.search(
        r'^Revision:\s+(\S+)', (spec_dir / 'SOURCE').read_text(), re.M
    )
    revision = revision.group(1) if revision else 'unknown'
    header = (
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        '<!--\n'
        '  GENERATED by scripts/gen-mpris-interface.py. Do not edit by hand.\n'
        '  Plain D-Bus introspection XML of the MPRIS D-Bus Interface Specification,\n'
        '  input of gdbus-codegen (playerctl/meson.build).\n'
        '  Source: https://gitlab.freedesktop.org/mpris/mpris-spec/-/tree/%s/spec\n'
        '  Vendored copy: doc/specs/mpris/\n'
        '-->\n' % revision
    )
    out_path.write_text(header + body + '\n')
    print('wrote %s' % out_path.relative_to(root), file=sys.stderr)


if __name__ == '__main__':
    main()
