#!/usr/bin/env python3
"""Turn a D-Bus introspection XML file into a C header for playerctld.

Usage: gen-introspection-header.py INPUT OUTPUT --variable NAME
           [--exclude INTERFACE.MEMBER ...] [--deprecated-alias SRC=DST ...]

Writes `static const char NAME[]` holding INPUT without the excluded methods,
signals and properties, plus a copy of each SRC interface named DST and marked
`org.freedesktop.DBus.Deprecated`. Run by meson (playerctl/meson.build) on the
interface XML files in data/, so playerctld announces what they define (the MPRIS
specification, minus what it does not forward, and its own interface). Excluding
a member or aliasing an interface that INPUT does not have is an error, so a
renamed or removed one cannot go unnoticed. Standard library only: this runs on
every build.
"""

import argparse
import copy
import os
import re
import sys
import xml.etree.ElementTree as ET

MEMBER_KINDS = ('method', 'signal', 'property')


def exclude_member(node, spec):
    interface_name, _, member = spec.rpartition('.')
    interface = node.find("interface[@name='%s']" % interface_name)
    if interface is None:
        raise SystemExit('cannot exclude %s: no interface %s' % (spec, interface_name))
    found = [
        element
        for kind in MEMBER_KINDS
        for element in interface.findall("%s[@name='%s']" % (kind, member))
    ]
    if not found:
        raise SystemExit('cannot exclude %s: no such member' % spec)
    for element in found:
        interface.remove(element)


def add_deprecated_alias(node, spec):
    source, _, alias = spec.partition('=')
    interface = node.find("interface[@name='%s']" % source)
    if interface is None:
        raise SystemExit('cannot alias %s: no interface %s' % (spec, source))
    if node.find("interface[@name='%s']" % alias) is not None:
        raise SystemExit('cannot alias %s: interface %s already exists' % (spec, alias))
    clone = copy.deepcopy(interface)
    clone.set('name', alias)
    deprecated = ET.Element(
        'annotation',
        {'name': 'org.freedesktop.DBus.Deprecated', 'value': 'true'},
    )
    clone.insert(0, deprecated)
    node.append(clone)


def c_literal(line):
    escaped = line.replace('\\', '\\\\').replace('"', '\\"')
    return '"%s\\n"' % escaped


def render(xml, source, variable):
    body = '\n'.join('    ' + c_literal(line) for line in xml.splitlines())
    return (
        '/* GENERATED by playerctl/gen-introspection-header.py from %s.\n'
        '   Do not edit. */\n'
        'static const char %s[]\n'
        '    = %s;\n' % (source, variable, body.lstrip())
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('input')
    parser.add_argument('output')
    parser.add_argument(
        '--variable',
        required=True,
        help='name of the C variable that holds the XML',
    )
    parser.add_argument(
        '--deprecated-alias',
        action='append',
        default=[],
        metavar='SRC=DST',
        help='add a copy of interface SRC named DST, marked deprecated (repeatable)',
    )
    parser.add_argument(
        '--exclude',
        action='append',
        default=[],
        metavar='INTERFACE.MEMBER',
        help='leave out a method, signal or property (repeatable)',
    )
    args = parser.parse_args()

    if not re.fullmatch(r'[A-Za-z_][A-Za-z0-9_]*', args.variable):
        raise SystemExit('--variable %s is not a C identifier' % args.variable)

    node = ET.parse(args.input).getroot()
    for spec in args.exclude:
        exclude_member(node, spec)
    for spec in args.deprecated_alias:
        add_deprecated_alias(node, spec)
    ET.indent(node, space='  ')
    xml = ET.tostring(node, encoding='unicode')

    with open(args.output, 'w') as output:
        output.write(render(xml, os.path.basename(args.input), args.variable))


if __name__ == '__main__':
    sys.exit(main())
